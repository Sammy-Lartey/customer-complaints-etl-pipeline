"""
generate_client_seed.py
Generates dummy public.client data -- simulates the external CRM/core-banking
system this pipeline is based on but doesn't own. Run manually, not part of
the DAG (this represents a system we don't control).

Samples ~60% phone-number overlap from the synthetic source workbook
(data/source/CUSTOMER_SUPPORT-2025.xlsx, itself generated by
generate_synthetic_source.py) -- both sides are fully synthetic.

Run generate_synthetic_source.py first if data/source/ doesn't exist yet.

Outputs sql/init/01_seed_client.sql for local Docker init.
"""

